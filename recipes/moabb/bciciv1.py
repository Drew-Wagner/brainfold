"""BCI Competition IV, data set 1 (Blankertz et al., 2007) as a MOABB dataset: visual cues to train, spoken cues to test.

Each subject did two motor imagery classes of left hand, right hand and foot
(different pairs for different subjects), in one sitting:

- calibration (session "0calibration"): 2 runs, arrows shown for 4 s as cues,
  4 s of fixation cross and blank screen between them; 100 trials per class.
- evaluation (session "1evaluation"): 4 runs, the class cued by a soft spoken
  word ("left", "right", "foot"), imagery for 1.5-8 s until the word "stop",
  then rest for 1.5-8 s. The classes aren't balanced.

A trial is the cue's onset with the subject's class one or two (labels 0 and 1).
The evaluation data has no markers; its cues come from the published true labels
(true_y, per 1000 Hz sample: -1, 1, 0 for rest, NaN for the 1 s after each cue),
where each cue starts a NaN run. Only evaluation trials whose imagery lasts at
least ``min_duration`` seconds are kept (by default the 4 s of the interval, so
that no window contains the "stop" cue). The competition's own task (continuous
output, rest included, scored by squared error) isn't reproduced.

Subjects 1-7 are the competition's a-g. c, d and e (3, 4, 5) are artificial
data, generated by the organisers; they are left out unless ``subjects`` asks
for them.

Data: the 1000 Hz MAT files (BCICIV_1calib_1000Hz_mat.zip and
BCICIV_1eval_1000Hz_mat.zip, from https://www.bbci.de/competition/iv/ after
accepting its terms) and the true labels (results/ds1/true_labels.zip), unzipped
into one directory: $BCICIV1_PATH, or $MNE_DATA/BCICIV_1 (~/mne_data/BCICIV_1). The recordings are
resampled to ``sfreq`` (250 Hz, as BNCI2014001) when loaded; MOABB's paradigm
then band-passes and resamples them as for any dataset. Signals are microvolts
(int16 x 0.1), returned in volts.

Berlin's channel names are mapped to the 10-5 system's (CFC3 -> FCC3, CFC7 ->
FTT7, CCP7 -> TTP7, ...) for the montage, which SpeechBrain-MOABB's channel
selection (adjacency steps from Cz) needs.
"""

from __future__ import annotations

import os
from pathlib import Path

import mne
import numpy as np
from moabb.datasets.base import BaseDataset

LETTERS = "abcdefg"
REAL = [1, 2, 6, 7]  # a, b, f, g; c, d, e are artificial
INTERVAL = [0, 4]


def ten_five(name):
    """The 10-5 name of a Berlin channel label."""
    for old, new in (("CFC7", "FTT7"), ("CFC8", "FTT8"), ("CCP7", "TTP7"), ("CCP8", "TTP8"), ("CFC", "FCC")):
        if name.startswith(old):
            return new + name[len(old):]
    return name


def evaluation_cues(true_y, fs):
    """(onset sample, label -1 or 1, imagery seconds) per class cue of the evaluation labels.

    A cue starts each run of NaN (the 1 s after it); a class cue's NaN run is
    followed by -1 or 1, and its imagery lasts until the next NaN run (the "stop").
    """
    nan = np.isnan(true_y)
    edges = np.flatnonzero(np.diff(np.r_[0, nan.astype(np.int8), 0]))
    starts, stops = edges[::2], edges[1::2]  # NaN runs [start, stop)
    cues = []
    for i, (start, stop) in enumerate(zip(starts, stops)):
        if stop >= len(true_y) or true_y[stop] == 0:
            continue
        end = starts[i + 1] if i + 1 < len(starts) else len(true_y)
        cues.append((int(start), int(true_y[stop]), (end - start) / fs))
    return cues


class BCICIV1(BaseDataset):
    """BCI Competition IV data set 1: calibration with visual cues, evaluation with spoken cues."""

    def __init__(self, subjects=None, min_duration=4.0, sfreq=250.0, path=None):
        super().__init__(subjects=list(range(1, 8)), sessions_per_subject=2,
                         events=dict(class_one=1, class_two=2), code="BCICIV1", interval=INTERVAL,
                         paradigm="imagery", doi="10.1016/j.neuroimage.2007.01.051")
        self.subject_list = list(subjects or REAL)  # BaseDataset's default list is every subject
        self.min_duration, self.sfreq = min_duration, sfreq
        self.path = Path(path or os.environ.get(
            "BCICIV1_PATH", Path(os.environ.get("MNE_DATA", Path.home() / "mne_data")) / "BCICIV_1"))
        self.classes = {}  # subject: (class one, class two), e.g. ("left", "foot")
        self.dropped = {}  # subject: evaluation cues dropped for lasting under min_duration

    def _file(self, part, letter, suffix=""):
        """The 1000 Hz MAT file of ``part`` (calib, eval) for subject ``letter``, anywhere under the path."""
        found = sorted(p for p in self.path.rglob(f"*{part}*ds1{letter}*.mat")
                       if ("true_y" in p.name) == (suffix == "true_y") and "100Hz" not in p.name)
        if not found:
            raise FileNotFoundError(f"no {part} {suffix} MAT file of subject {letter} under {self.path}: download and "
                                    "unzip BCI Competition IV data set 1 (1000 Hz, MAT) and its true labels there "
                                    "(see bciciv1.py)")
        return found[0]

    def _raw(self, cnt, nfo, events):
        """A Raw of the EEG in volts at ``sfreq``, with the events (sample at 1000 Hz, code) in a stim channel."""
        fs = float(nfo["fs"])
        names = [ten_five(str(c)) for c in nfo["clab"]]
        raw = mne.io.RawArray(cnt.T.astype(np.float64) * 0.1e-6, mne.create_info(names, fs, "eeg"), verbose=False)
        raw.set_montage("standard_1005", on_missing="raise")
        if fs != self.sfreq:
            raw.resample(self.sfreq, verbose=False)
        stim = np.zeros((1, raw.n_times))
        stim[0, np.round(events[:, 0] * self.sfreq / fs).astype(int)] = events[:, 1]
        raw.add_channels([mne.io.RawArray(stim, mne.create_info(["stim"], self.sfreq, "stim"), verbose=False)],
                         force_update_info=True)
        return raw

    def _get_single_subject_data(self, subject):
        from scipy.io import loadmat

        letter = LETTERS[subject - 1]
        calib = loadmat(self._file("calib", letter), squeeze_me=True, struct_as_record=False)
        evalm = loadmat(self._file("eval", letter), squeeze_me=True, struct_as_record=False)
        true_y = loadmat(self._file("eval", letter, "true_y"), squeeze_me=True)["true_y"]
        nfo = {k: getattr(calib["nfo"], k) for k in ("fs", "clab", "classes")}
        self.classes[subject] = tuple(str(c) for c in nfo["classes"])
        assert float(nfo["fs"]) == 1000, nfo["fs"]

        mrk = calib["mrk"]
        calib_events = np.c_[np.asarray(mrk.pos, int) - 1, np.where(np.asarray(mrk.y) < 0, 1, 2)]  # MATLAB's 1-based

        cnt = evalm["cnt"]
        n = min(len(cnt), len(true_y))  # subject a's labels may be longer than an early download of its data
        cues = evaluation_cues(true_y[:n], 1000.0)
        kept = [(s, y) for s, y, d in cues if d >= self.min_duration and s + INTERVAL[1] * 1000 <= n]
        self.dropped[subject] = len(cues) - len(kept)
        eval_events = np.array([(s, 1 if y < 0 else 2) for s, y in kept], int)
        return {"0calibration": {"0": self._raw(calib["cnt"], nfo, calib_events)},
                "1evaluation": {"0": self._raw(cnt[:n], nfo, eval_events)}}

    def data_path(self, subject, path=None, force_update=False, update_path=None, verbose=None):
        letter = LETTERS[subject - 1]
        return [str(self._file(part, letter, suffix)) for part, suffix in (("calib", ""), ("eval", ""), ("eval", "true_y"))]
